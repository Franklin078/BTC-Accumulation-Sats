md("## 3. How the model works, and why it beats uniform DCA\n\n"
   "**Features.** Three inputs, each computable on the day it is used: the ratio of 30-day "
   "to 365-day average hash rate, the same ratio for total transaction fees, and the cosine "
   "position within the 4-year halving cycle. All are lagged one day, so the weight for day "
   "t is fixed at the close of day t-1.\n\n"
   "**Decision mechanism.** A HistGradientBoosting regressor, refit every 90 days on an "
   "expanding window of fully closed labels, forecasts the 90-day forward log return. The "
   "forecast is standardised against the expanding mean and deviation of its own past "
   "values, clipped, and mapped to a bounded daily multiplier; the asymmetric variants tilt "
   "harder into buy signals than caution signals. The pacing allocator spends the even pace "
   "of the remaining budget scaled by that multiplier, so constraint satisfaction is "
   "structural, not corrected after the fact.\n\n"
   "**Why it wins.** Usage momentum leads price at the quarterly horizon in this data, and "
   "the recency-weighted metric rewards conviction: raising the multiplier ceiling from 5 to "
   "12 was the single largest scoring improvement in the study. Blends, wider feature sets, "
   "alternative learners, sentiment data and learned modulators were all tested in "
   "registered rounds and all lost to this simple engine; the full record, losers included, "
   "is in [notebook 08](../notebooks/08_feature_ml_ranking.ipynb), "
   "[notebook 09](../notebooks/09_rounds6to9.ipynb) and "
   "[notebook 10](../notebooks/10_rounds10to12.ipynb).\n\n"
   "**Why it should generalise.** Causality is enforced, not assumed: the tournament's "
   "forward-leakage probe retrains the whole pipeline under masked data at 51 dates and "
   "requires identical weights. Selection used an early development period separated from "
   "later data by a 12-month embargo, robustness was measured (no single pre-2024 year "
   "carries the result; the stable finalists move under one point when any parameter is "
   "perturbed alone), and every learner number is reported under two library versions.")
