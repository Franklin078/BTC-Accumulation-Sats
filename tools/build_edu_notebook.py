   "Uniform dollar cost averaging buys the same amount of Bitcoin every day. This study asks "
   "whether a rule that varies the daily amount, using only information available at the "
   "time, accumulates more satoshis per dollar over rolling 12-month windows, judged by the "
   "Trilemma Foundation's published scoring framework (Final Model Score = 0.5 x win rate + "
   "0.5 x recency-weighted percentile of satoshis per dollar).\n\n"
   "**The approach.** The model forecasts the 90-day forward return with a small "
   "gradient-boosted learner trained on three signals the data itself ranked first: hash-rate "
   "momentum, transaction-fee momentum, and position in the halving calendar. Training is "
   "purged walk-forward (a model refit every 90 days sees only samples whose outcome had "
   "fully closed), the forecast is standardised against its own past only, and a "
   "remaining-budget pacing allocator turns it into daily weights that satisfy the "
   "tournament's constraints by construction: every weight above the minimum, every window "
   "summing to one, no forward information anywhere. The tournament's own leakage probe, "
   "which masks the future and demands unchanged weights, passes 51 of 51 dates on every "
   "reported model.\n\n"
